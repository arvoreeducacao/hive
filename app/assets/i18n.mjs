export const SAID = { "pt-BR": PT_BR };

const SLOT = /\{(\w+)\}/g;

export function fill(text, vars) {
  if (!vars) return text;
  return String(text).replace(SLOT, (whole, key) => (key in vars ? String(vars[key]) : whole));
}

let spoken = DEFAULT_LANGUAGE;

export function speak(id) {
  spoken = isLanguage(id) ? id : DEFAULT_LANGUAGE;
  return spoken;
}

export const spokenNow = () => spoken;

export function phrase(text, vars) {
  const said = SAID[spoken]?.[text] ?? text;
  return fill(said, vars);
}

export const T_ATTRS = ["title", "aria-label", "placeholder"];

const asWritten = new WeakMap();

function sourceOf(node, key, value) {
  let mine = asWritten.get(node);
  if (!mine) asWritten.set(node, (mine = new Map()));
  if (!mine.has(key)) mine.set(key, value);
  return mine.get(key);
}

const SILENT = new Set(["SCRIPT", "STYLE", "SVG"]);
const KEEPS_ITS_TEXT = new Set(["TEXTAREA"]);

function sayHere(el, say) {
  if (SILENT.has(el.tagName)) return;
  if (el.hasAttribute("data-no-t")) return sayAttrs(el, say);
  if (KEEPS_ITS_TEXT.has(el.tagName)) return sayAttrs(el, say);
  for (const node of el.childNodes) {
    if (node.nodeType !== 3) continue;
    const written = sourceOf(node, "text", node.nodeValue);
    const said = written.trim();
    if (said) node.nodeValue = written.replace(said, say(said));
  }
  sayAttrs(el, say);
  for (const child of el.children) sayHere(child, say);
}

function sayAttrs(el, say) {
  for (const attr of T_ATTRS) {
    if (!el.hasAttribute(attr)) continue;
    const written = sourceOf(el, attr, el.getAttribute(attr));
    if (written.trim()) el.setAttribute(attr, say(written.trim()));
  }
}

export function paintStatic(root, say = phrase) {
  for (const el of root.querySelectorAll("[data-t]")) sayHere(el, say);
}

export function paintNodes(nodes, say = phrase) {
  for (const el of nodes) sayHere(el, say);
}
